"""Generate the data dictionary (docs/DATA_DICTIONARY.md and reports/data_dictionary.xlsx) from the live database.

Table and column meanings come from two small files you can edit: docs/table_notes.csv and docs/column_notes.csv.
Columns without a note are listed with an empty meaning so the gaps are visible.

Run:  python scripts/10_generate_data_dictionary.py
"""
import os
import csv
from pathlib import Path

import psycopg
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill

ROOT = Path(__file__).resolve().parent.parent
DB = "dbname=" + (os.environ.get("RENTAL_DB") or os.environ.get("PGDATABASE") or "rental_dwh")
SCHEMAS = [("gold", "Finished tables (read these)"), ("entry", "Direct-entry tables (type into these)")]


def load(path, key):
    with open(path, newline="", encoding="utf-8") as f:
        return {r[key]: r for r in csv.DictReader(f)}


def main():
    tables = load(ROOT / "docs" / "table_notes.csv", "table_name")
    cols = load(ROOT / "docs" / "column_notes.csv", "column_name")
    md = ["# Data dictionary", "", "Generated by `scripts/10_generate_data_dictionary.py` from the live database. "
          "Edit `docs/table_notes.csv` and `docs/column_notes.csv`, not this file.", ""]
    wb = Workbook()
    ws = wb.active
    ws.title = "Columns"
    ws.append(["Schema", "Table", "Table meaning", "表说明", "Column", "Type", "Meaning", "中文含义"])
    for c in ws[1]:
        c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="1F3864")
    missing = 0
    with psycopg.connect(DB) as conn, conn.cursor() as cur:
        for schema, title in SCHEMAS:
            cur.execute("""select c.table_name, c.column_name, c.data_type
                           from information_schema.columns c join information_schema.tables t using (table_schema, table_name)
                           where c.table_schema = %s order by c.table_name, c.ordinal_position""", (schema,))
            rows = cur.fetchall()
            md += [f"## {schema} - {title}", ""]
            current = None
            for t, col, typ in rows:
                if t.startswith(("stg_", "_")):
                    continue
                if t != current:
                    current = t
                    tn = tables.get(t, {})
                    md += ["", f"### {schema}.{t}", "", tn.get("description", "(no description yet)") + (f"  \n{tn['description_zh']}" if tn.get("description_zh") else ""), "",
                           "| Column | Type | Meaning |", "|---|---|---|"]
                cn = cols.get(col, {})
                if not cn:
                    missing += 1
                zh = f" / {cn['meaning_zh']}" if cn.get("meaning_zh") else ""
                md.append(f"| `{col}` | {typ} | {cn.get('meaning', '')}{zh} |")
                ws.append([schema, t, tables.get(t, {}).get("description", ""), tables.get(t, {}).get("description_zh", ""),
                           col, typ, cn.get("meaning", ""), cn.get("meaning_zh", "")])
    for col_letter, w in zip("ABCDEFGH", [9, 30, 50, 30, 32, 16, 60, 40]):
        ws.column_dimensions[col_letter].width = w
    ws.freeze_panes = "A2"
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (ROOT / "reports").mkdir(exist_ok=True)
    wb.save(ROOT / "reports" / "data_dictionary.xlsx")
    print(f"Wrote docs/DATA_DICTIONARY.md and reports/data_dictionary.xlsx ({ws.max_row - 1} columns, {missing} without a note)")


if __name__ == "__main__":
    main()
